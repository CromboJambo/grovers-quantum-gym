/// David Deutsch: The Fabric of Reality and the Growth of Knowledge
/// Based on his work connecting Many-Worlds, computation, evolution,
/// and Popperian epistemology. Directly connects to the user's themes
/// about learning from being wrong and problem propagation.

pub fn show_deutsch_station() {
    println!("=== DAVID DEUTSCH: THE FABRIC OF REALITY (1997) ===");
    println!();
    print_introduction();
    println!();
    demonstrate_four_strands();
    println!();
    demonstrate_good_explanations();
    println!();
    conclude_beginning_of_infinity();
}

fn print_introduction() {
    println!("David Deutsch is a British physicist at Oxford who's often called");
    println!("the 'father of quantum computing.' He formulated the first description");
    println!("of a universal quantum computer in 1981-82.");
    println!();
    println!("But here's what makes him interesting to us: he wrote a book called");
    println!("The Fabric of Reality that ties together four completely different");
    println!("areas of thought into one unified picture of how reality works.");
    println!();
    println!("And it connects directly to something we've been discussing — the idea");
    println!("that knowledge grows through conjecture and refutation. Through being");
    println!("wrong, then correcting ourselves.");
}

fn demonstrate_four_strands() {
    println!("--- THE FOUR STRANDS OF REALITY ---");
    println!();
    println!("Deutsch argues that reality is woven from four interwoven strands:");
    println!();
    println!("1. QUANTUM PHYSICS (Many-Worlds Interpretation)");
    println!("   Reality is fundamentally quantum. The universe splits into branches.");
    println!("   Every possibility exists somewhere in the multiverse.");
    println!();
    println!("2. EPISTEMOLOGY (Karl Popper's Philosophy of Science)");
    println!("   Knowledge grows through conjecture and refutation. We propose bold");
    println!("   explanations, then try to falsify them. Progress comes from finding");
    println!("   our errors, not from accumulating verified truths.");
    println!();
    println!("3. COMPUTATION (Alan Turing's Theory)");
    println!("   The universe is computational. Physical processes can be understood");
    println!("   as information processing. A universal computer can simulate any");
    println!("   physical process given enough time and resources.");
    println!();
    println!("4. EVOLUTION (Charles Darwin's Theory)");
    println!("   The same error-correcting principle applies to biology: variation");
    println!("   produces diversity, selection eliminates unfit variants. Evolution");
    println!("   is nature's way of learning from mistakes.");
    println!();
    println!("The deep insight: all four strands share the same fundamental pattern.");
    println!("Reality itself is an error-correcting system that generates knowledge");
    println!("through a cycle of variation and selection.");

    // Demonstrate the shared pattern
    println!();
    println!("Example: The shared pattern across all four strands");
    println!("-----------------------------------------------");

    let examples = [
        (
            "Quantum",
            "Superposition of states → measurement selects one outcome",
        ),
        (
            "Epistemology",
            "Multiple hypotheses → evidence eliminates wrong ones",
        ),
        (
            "Computation",
            "Branching paths in algorithm → backtracking finds solution",
        ),
        (
            "Evolution",
            "Genetic variation → natural selection removes unfit",
        ),
    ];

    for (domain, pattern) in examples {
        println!("  {}: {}", domain, pattern);
    }

    println!();
    println!("Same fundamental process: generate possibilities, eliminate the bad ones.");
}

fn demonstrate_good_explanations() {
    println!("--- WHAT MAKES A GOOD EXPLANATION? ---");
    println!();
    println!("Deutsch has a famous criterion for good explanations. In his book");
    println!("The Beginning of Infinity (2011), he says:");
    println!();
    println!("  'Good explanations are hard to vary.'");
    println!();
    println!("What does that mean? It means a good explanation has deep structure.");
    println!("If you try to change it slightly, it breaks. You can't just tweak it");
    println!("to fit new data — the whole thing would fall apart.");
    println!();
    println!("Compare:");
    println!();
    println!("Bad explanation (easy to vary): 'The bird flies because it has wings.'");
    println!("  → You could say 'because it has feathers' or 'because it's light.'");
    println!("  → No deep structure, just a description.");
    println!();
    println!("Good explanation (hard to vary): 'Birds fly due to lift generated by");
    println!("  airfoil-shaped wings creating pressure differentials per Bernoulli's");
    println!("  principle and Newton's third law.'");
    println!("  → Change any part and the explanation breaks.");
    println!();
    println!("This connects to our discussion about Gödel: a good formal system has");
    println!("deep structure. You can't just add axioms willy-nilly — they have to fit");
    println!("the whole architecture. And that's why extending the system creates new");
    println!("undecidable statements: the structure forces them.");

    // Demonstrate with a simple example
    println!();
    println!("Example: Why does water boil at 100°C at sea level?");
    println!("Easy to vary (bad): 'Because it's hot.' → Could say 'because it's wet.'");
    println!("Hard to vary (good): 'Because at 1 atm pressure, the vapor pressure of");
    println!("water equals atmospheric pressure at exactly 373.15 K.' → Change any part");
    println!("and it's wrong.");
}

fn conclude_beginning_of_infinity() {
    println!("--- THE BEGINNING OF INFINITY ---");
    println!();
    println!("Deutsch's conclusion is stunning: knowledge growth is unbounded.");
    println!("There's no final answer, no end of learning. Every explanation opens");
    println!("new questions. Every solution generates new problems.");
    println!();
    println!("This echoes what we discussed earlier: 'problems propagate with solutions.'");
    println!("Deutsch would say that's not a bug — it's a feature. It means the universe");
    println!("is fundamentally open-ended, creative, and evolving.");
    println!();
    println!("And here's the connection to quantum mechanics: in Many-Worlds, every");
    println!("possibility is realized somewhere. The multiverse is literally infinite");
    println!("in its variety. Deutsch sees this as proof that reality is fundamentally");
    println!("about possibility and potential, not just actuality.");
    println!();
    println!("So when you solve a problem and feel that relaxation — that celebration");
    println!("of collapse — Deutsch would say: good job. But don't stop. Because the");
    println!("multiverse is still splitting, new branches are forming, and there's always");
    println!("more to learn.");
    println!();
    println!("As he puts it: 'The universe is not only queerer than we suppose, but");
    println!("queerer than we CAN suppose.'")
}

